// ═══ 4. WebSocket feed ═══

function connectWebSocket() {
  const protocol = window.location.protocol === 'https:' ? 'wss:' : 'ws:';
  const wsUrl = `${protocol}//${window.location.host}/ws/feed`;

  try {
    const socket = new WebSocket(wsUrl);
    socket.onopen = () => {
      wsConnected = true;
      document.getElementById('network-status').innerText = 'Realtime Protocol Active (WS Connected)';
    };
    socket.onmessage = (msg) => {
      try {
        handleWsEvent(JSON.parse(msg.data));
      } catch {}
    };
    socket.onclose = () => {
      wsConnected = false;
      document.getElementById('network-status').innerText = 'NPCI UAP / UPI Reserve Pay Simulator';
      setTimeout(connectWebSocket, 3000);
    };
  } catch (err) {
    console.warn('WS connection failed:', err);
  }
}

// ═══ 5. Conversational Autonomous Checkout ═══

function initChat() {
  const sendBtn = document.getElementById('chat-send-btn');
  const input = document.getElementById('chat-input');

  sendBtn.addEventListener('click', () => submitChatMessage(input.value.trim()));

  input.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      submitChatMessage(input.value.trim());
    }
  });

  document.querySelectorAll('#chat-chips .chip').forEach((chip) => {
    chip.addEventListener('click', () => {
      input.value = chip.getAttribute('data-prompt');
      submitChatMessage(input.value);
    });
  });
}

async function submitChatMessage(message) {
  if (!message) return;
  const input = document.getElementById('chat-input');
  const sendBtn = document.getElementById('chat-send-btn');

  input.value = '';
  appendChatBubble('user', 'You', message);
  const typingEl = showTypingIndicator();

  sendBtn.disabled = true;
  input.disabled = true;

  try {
    const res = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ sessionId: chatSessionId || undefined, message }),
    });

    const data = await res.json();
    typingEl.remove();

    if (!data.ok) {
      appendChatBubble('system', 'System', data.error || 'Checkout failed — see server logs.');
    }

    chatSessionId = data.sessionId;
    renderTranscriptTail(data.transcript);

    if (data.budget) updateBudgetMeter(data.budget);

    const settled = [...(data.transcript || [])].reverse().find((e) => e.kind === 'SETTLED');
    if (settled && settled.meta?.receipt) {
      mirrorSettlementToDashboard(settled.meta.receipt);
    } else {
      const rejected = [...(data.transcript || [])].reverse().find((e) => e.kind === 'REJECTED');
      if (rejected) showErrorToast('Quote rejected: ' + (rejected.rationale || 'bounds violation'));
    }
  } catch (err) {
    typingEl.remove();
    appendChatBubble('system', 'Connection Error', err.message);
  } finally {
    sendBtn.disabled = false;
    input.disabled = false;
    input.focus();
  }
}

function appendChatBubble(actor, senderLabel, text, rationaleCardHtml = '') {
  const thread = document.getElementById('chat-thread');
  if (thread.querySelector('div[style]') && !thread.querySelector('.feed-item')) thread.innerHTML = '';

  const itemEl = document.createElement('div');
  itemEl.className = `feed-item ${actor === 'user' ? 'buyer' : actor === 'system' ? 'merchant' : actor}`;
  itemEl.innerHTML = `
    <div class="feed-header"><span>${senderLabel}</span></div>
    <div class="feed-bubble">
      <div class="feed-json-snippet">${escapeHtml(text)}</div>
      ${rationaleCardHtml}
    </div>`;
  document.getElementById('chat-thread').appendChild(itemEl);
  thread.scrollTop = thread.scrollHeight;
  return itemEl;
}

function renderTranscriptTail(transcript) {
  if (!Array.isArray(transcript)) return;
  const domSeqs = new Set(
    Array.from(document.querySelectorAll('#chat-thread .feed-item[data-tseq]')).map((el) =>
      parseInt(el.getAttribute('data-tseq'), 10)
    )
  );
  const pending = transcript.filter((e) => e.seq !== undefined && !domSeqs.has(e.seq));

  for (const evt of pending) {
    if (evt.kind === 'USER_MESSAGE') continue;
    const actorLabel =
      evt.actor === 'buyer' ? '🤖 Buyer Agent' :
      evt.actor === 'merchant' ? '🏬 Merchant Agent' : '⚙️ Protocol';
    const rationaleHtml = evt.rationale
      ? `<div class="rationale-card"><strong>Why:</strong> ${escapeHtml(evt.rationale)}</div>`
      : '';
    const bubble = appendChatBubble(evt.actor, actorLabel, `${evt.title}${evt.detail ? '\n' + evt.detail : ''}`, rationaleHtml);
    bubble.setAttribute('data-tseq', evt.seq);
    const badge = bubble.querySelector('.feed-header span');
    if (badge && evt.source) badge.innerHTML += ` <small style="opacity:.6">(${evt.source})</small>`;
  }
}

function updateBudgetMeter(budget) {
  const pct = budget.capPaise > 0 ? Math.max(0, (budget.remainingPaise / budget.capPaise) * 100) : 0;
  document.getElementById('chat-budget-fill').style.width = `${pct}%`;
  document.getElementById('chat-budget-text').innerText =
    `₹${(budget.remainingPaise / 100).toFixed(2)} remaining of ₹${(budget.capPaise / 100).toFixed(2)}`;
}

function mirrorSettlementToDashboard(receipt) {
  document.getElementById('res-order-id').innerText = receipt.razorpayOrderId;
  document.getElementById('res-payment-id').innerText = receipt.razorpayPaymentId;
  document.getElementById('res-amount').innerText = `₹${(receipt.amount / 100).toFixed(2)}`;
  document.getElementById('res-mandate-ref').innerText = receipt.uapMandateRef;
  setTimelineActiveStep(8);
  document.getElementById('fsm-current-state').innerText = 'STATE: SETTLED & VERIFIED';
}

