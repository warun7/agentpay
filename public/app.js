// ═══ 1. Identities + gateway mode chip ═══

async function initIdentities() {
  try {
    const res = await fetch('/api/identities');
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    if (data.merchant) {
      document.getElementById('merchant-name').innerText = data.merchant.name;
      document.getElementById('merchant-did').innerText = truncateDID(data.merchant.did);
      document.getElementById('merchant-did').onclick = () => copyToClipboard(data.merchant.did);
      document.getElementById('merchant-upi').innerText = data.merchant.upiId || 'agentpay.merchant@razorpay';
    }

    // Gateway mode chip — honest split of order creation vs capture
    const chip = document.getElementById('gateway-mode-chip');
    if (chip && data.orderCreationMode) {
      const orderTxt = data.orderCreationMode === 'live-test-orders' ? 'Orders: RZP test LIVE' : 'Orders: mock';
      const capTxt = 'Capture: UAP-sim';
      const llmTxt = data.llmEnabled ? ` · LLM: ${data.activeModel}` : '';
      chip.innerText = `${data.gatewayMode === 'live' ? '⚡' : '🧪'} ${orderTxt} · ${capTxt}${llmTxt}`;
      chip.style.borderColor = data.gatewayMode === 'live' ? 'var(--feedback-positive)' : 'var(--surface-border-subtle)';
      chip.style.color = data.gatewayMode === 'live' ? 'var(--feedback-positive)' : 'var(--text-tertiary)';
    }
  } catch (err) {
    console.warn('Could not fetch initial identities:', err);
    document.getElementById('network-status').innerText = 'Server Reconnecting...';
  }
}

// ═══ 2. Cryptographic Proof Inspector tabs ═══

function initTabs() {
  const tabs = document.querySelectorAll('.tab-btn');
  tabs.forEach((tab) => {
    tab.addEventListener('click', () => {
      tabs.forEach((t) => t.classList.remove('active'));
      tab.classList.add('active');
      currentTab = tab.getAttribute('data-tab');
      renderInspector();
    });
  });

  document.getElementById('copy-proof-btn').addEventListener('click', () => {
    copyToClipboard(document.getElementById('inspector-code').innerText);
  });
}

function renderInspector() {
  const codeEl = document.getElementById('inspector-code');
  const digestEl = document.getElementById('inspector-digest');

  if (!currentProofBundle) {
    codeEl.innerText = '// Execute a transaction to inspect live cryptographic proofs.';
    digestEl.innerText = 'SHA-256 Digest: —';
    return;
  }

  let content = {};
  switch (currentTab) {
    case 'jws':
      content = {
        description: 'Detached Ed25519 JSON Web Signature generated by Buyer Agent',
        transactionId: currentProofBundle.signedTransaction.transactionId,
        buyerDID: currentProofBundle.signedTransaction.buyerDID,
        amountPaise: currentProofBundle.signedTransaction.amount,
        nonce: currentProofBundle.signedTransaction.nonce,
        jwsSignature: currentProofBundle.signedTransaction.jwsSignature,
        algorithm: 'EdDSA (RFC 8037)',
        verificationStatus: 'MATHEMATICALLY_VERIFIED_VALID',
      };
      break;
    case 'vc':
      content = currentProofBundle.mandateCredential;
      break;
    case 'ecdh':
      content = {
        keyAgreementSuite: 'X25519KeyAgreementKey2020',
        symmetricCipher: 'AES-256-GCM (Authenticated Encryption with Associated Data)',
        keyDerivation: 'HKDF-SHA256 (RFC 5869)',
        perfectForwardSecrecy: true,
        buyerKeyAgreementJwk: currentProofBundle.mandateCredential.credentialSubject.id,
        merchantDID: currentProofBundle.merchantDID,
      };
      break;
    case 'razorpay':
      content = {
        razorpayOrder: currentProofBundle.razorpayOrder,
        paymentResult: currentProofBundle.paymentResult,
        paymentSignature: currentProofBundle.paymentSignature,
        uapMandateRef: currentProofBundle.mandateCredential.credentialSubject.uapMandateCircleRef,
        hmacSha256Verified: true,
      };
      break;
  }

  codeEl.innerText = JSON.stringify(content, null, 2);
  digestEl.innerText = `Audit Digest: ${currentProofBundle.auditTrailDigest || 'Calculated'}`;
}

// ═══ 3. One-click autonomous checkout (WS-driven visualization) ═══

function initControls() {
  const runBtn = document.getElementById('run-checkout-btn');
  const select = document.getElementById('catalog-select');

  runBtn.addEventListener('click', async () => {
    runBtn.disabled = true;
    runBtn.innerHTML = `<span style="display:inline-block;animation:pulseDot 1s infinite">⚡</span> Executing Autonomous Protocol...`;

    resetVisuals();
    awaitingRun = true; // first RUN_STARTED event binds the view to that run
    wsEventsThisRun = 0;

    try {
      const itemId = select.value;
      const res = await fetch('/api/demo/run', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ itemId }),
      });

      if (!res.ok) {
        const errorText = await res.text();
        throw new Error(`Server returned HTTP ${res.status}: ${errorText}`);
      }

      const data = await res.json();
      if (!data.success) {
        showErrorToast('Transaction failed: ' + data.error);
        return;
      }

      currentProofBundle = data.proofBundle;

      // Give late WS frames a beat, then decide renderer
      await sleep(400);
      if (wsEventsThisRun === 0 || !wsConnected) {
        await animateWorkflowFallback(data); // offline/canned path
      } else {
        setTimelineActiveStep(8);
        document.getElementById('fsm-current-state').innerText = 'STATE: SETTLED & VERIFIED';
      }

      renderSummary(data);

      // Mirror into proof inspector
      currentProofBundle = data.proofBundle;
      renderInspector();

    } catch (err) {
      console.error('Error executing checkout:', err);
      showErrorToast(`Connection Error: ${err.message}. Is the server running on port 3000?`);
    } finally {
      runBtn.disabled = false;
      runBtn.innerHTML = `
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><polygon points="13 2 3 14 12 14 11 22 21 10 12 10 13 2"/></svg>
        Execute Autonomous Checkout
      `;
    }
  });
}

function renderSummary(data) {
  document.getElementById('res-order-id').innerText = data.razorpayOrderId;
  document.getElementById('res-payment-id').innerText = data.razorpayPaymentId;
  document.getElementById('res-amount').innerText = `₹${(data.amount / 100).toFixed(2)}`;
  document.getElementById('res-mandate-ref').innerText = data.receipt.uapMandateRef;

  document.getElementById('buyer-did').innerText = truncateDID(data.buyerDID);
  document.getElementById('buyer-did').onclick = () => copyToClipboard(data.buyerDID);
}

function resetVisuals() {
  document.getElementById('chat-feed').innerHTML = '';
  document.querySelectorAll('.fsm-node').forEach((node) => node.classList.remove('active', 'completed'));
  document.querySelectorAll('.timeline-step').forEach((step) => step.classList.remove('active', 'completed'));
}

function setFSMActiveState(stateName) {
  const nodes = document.querySelectorAll('.fsm-node');
  let found = false;
  nodes.forEach((n) => {
    const nodeState = n.getAttribute('data-state');
    if (nodeState === stateName) {
      n.classList.remove('completed');
      n.classList.add('active');
      found = true;
    } else if (!found) {
      n.classList.remove('active');
      n.classList.add('completed');
    } else {
      n.classList.remove('active', 'completed');
    }
  });
  document.getElementById('fsm-current-state').innerText = `STATE: ${stateName}`;
}

function setTimelineActiveStep(stepNumber) {
  document.querySelectorAll('.timeline-step').forEach((s) => {
    const stepNum = parseInt(s.getAttribute('data-step'), 10);
    if (stepNum < stepNumber) {
      s.classList.remove('active');
      s.classList.add('completed');
    } else if (stepNum === stepNumber) {
      s.classList.remove('completed');
      s.classList.add('active');
    } else {
      s.classList.remove('active', 'completed');
    }
  });
}

// ── Live WS rendering ──

function appendFeedItem(senderLabel, title, detail, badgeClass = '', rationaleHtml = '') {
  const feed = document.getElementById('chat-feed');
  const itemEl = document.createElement('div');
  itemEl.className = `feed-item ${senderLabel.startsWith('🤖') ? 'buyer' : senderLabel.startsWith('⚙️') ? 'system' : 'merchant'}`;
  itemEl.innerHTML = `
    <div class="feed-header">
      <span>${senderLabel}</span>
      ${badgeClass ? `<span class="feed-badge ${badgeClass === 'Encrypted' ? 'enc' : ''}">${badgeClass}</span>` : ''}
    </div>
    <div class="feed-bubble">
      <strong>${title}</strong>
      <div class="feed-json-snippet">${escapeHtml(detail)}</div>
      ${rationaleHtml}
    </div>`;
  feed.appendChild(itemEl);
  feed.scrollTop = feed.scrollHeight;
  return itemEl;
}

function reasoningCard(reasoning) {
  const icon = reasoning.actor === 'buyer' ? '🤖' : '🏬';
  const clampWarn = reasoning.clamped
    ? `\n⚠️ Protocol clamp applied: ${(reasoning.discountRequested * 100).toFixed(1)}% → ${(reasoning.discountApplied * 100).toFixed(1)}%`
    : '';
  return `
    <div class="rationale-card">
      <strong>${icon} Why (${reasoning.stage}, ${reasoning.source}):</strong>
      ${escapeHtml(reasoning.rationale)}${clampWarn}
    </div>`;
}

function handleWsEvent(evt) {
  switch (evt.type) {
    case 'RUN_STARTED':
      if (awaitingRun) {
        activeRunId = evt.runId;
        wsEventsThisRun = 0;
        awaitingRun = false;
      }
      break;

    case 'FSM_TRANSITION': {
      if (evt.runId !== activeRunId) return;
      wsEventsThisRun++;
      const p = evt.payload;
      setFSMActiveState(p.toState);
      const tlStep = TIMELINE_FOR_STATE[p.toState];
      if (tlStep) setTimelineActiveStep(tlStep);

      const [actor, badge, label] = ACTION_LABELS[p.action] || ['⚙️ Protocol', '', p.action];
      const digest = p.payloadDigest ? ` · sha256:${String(p.payloadDigest).substring(0, 16)}…` : '';
      appendFeedItem(actor, `${p.action}`, `${label}${digest}`, badge);
      break;
    }

    case 'LLM_REASONING': {
      if (evt.runId !== activeRunId) return;
      wsEventsThisRun++;
      const who = evt.payload.actor === 'buyer' ? '🤖 Buyer Agent' : '🏬 Merchant Agent';
      const item = appendFeedItem(
        who,
        `AI decision — ${evt.payload.stage}`,
        evt.payload.rationale.split('\n')[0],
        'AI',
        reasoningCard(evt.payload)
      );
      break;
    }

    case 'RUN_COMPLETE': {
      if (evt.runId !== activeRunId) return;
      wsEventsThisRun++;
      appendFeedItem('✅ System', 'RUN COMPLETE', `Transaction ${evt.payload.transactionId} settled for ₹${(evt.payload.amount / 100).toFixed(2)}`);
      break;
    }

    case 'SETTLEMENT_CONFIRMED':
      appendFeedItem(
        '🔗 Settlement Confirmer',
        `Capture confirmed (${evt.source})`,
        `Order ${evt.razorpayOrderId} · confirmed at ${evt.confirmedAt || '—'}`
      );
      break;

    case 'CHAT_EVENT':
      // Chat panel renders via its own fetch transcript; nothing to do here.
      break;
  }
}

