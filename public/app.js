// AgentPay Frontend Dashboard Logic — live WebSocket-driven

let currentProofBundle = null;
let currentTab = 'jws';

// Live-run state
let wsConnected = false;
let awaitingRun = false;
let activeRunId = null;
let wsEventsThisRun = 0;
let chatSessionId = null;

const TIMELINE_FOR_STATE = {
  DID_EXCHANGED: 1,
  SESSION_ESTABLISHED: 2,
  MANDATE_VERIFIED: 3,
  CATALOG_RECEIVED: 4,
  INTENT_SENT: 5,
  QUOTE_RECEIVED: 5,
  SIGNED: 6,
  SETTLED: 7,
};

