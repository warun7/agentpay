  RECEIVE_BUYER_DID: ['Buyer Agent', 'Identity', 'DID document received & validated (did:key self-certifying)'],
  COMPLETE_ECDH_HANDSHAKE: ['Merchant Agent', 'Encrypted', 'X25519 ECDH complete — AES-256-GCM session tunnel active'],
  VERIFY_BUYER_MANDATE: ['Merchant Agent', 'Encrypted', 'Spending mandate VC verified: signature, expiry and bounds checked'],
