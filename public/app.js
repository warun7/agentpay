function showErrorToast(msg) {
  const feed = document.getElementById('chat-thread') || document.getElementById('chat-feed');
  const errEl = document.createElement('div');
  errEl.className = 'feed-item buyer';
  errEl.innerHTML = `
    <div class="feed-header">
      <span style="color: var(--feedback-negative)">⚠️ System Notification</span>
    </div>
    <div class="feed-bubble" style="border-color: var(--feedback-negative); background: var(--feedback-negative-bg)">
      <strong>Error</strong>
      <div class="feed-json-snippet" style="color: var(--feedback-negative)">${msg}</div>
    </div>`;
  feed.appendChild(errEl);
}

// Utilities
function truncateDID(did) {
  if (!did || did.length < 25) return did;
  return `${did.substring(0, 16)}...${did.substring(did.length - 8)}`;
}

function copyToClipboard(text) {
  navigator.clipboard.writeText(text);
  alert('Copied to clipboard!');
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function escapeHtml(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#039;');
}
